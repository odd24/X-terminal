import assert from 'node:assert/strict';
import {copyFile,mkdir,mkdtemp,readFile,rm,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {delay,launchDesktop} from './lib/DesktopHarness.mjs';
import {closeSoakDesktop} from './lib/LoadSoak.mjs';

const desktop=path.resolve(process.argv[2]);
const fixture=path.resolve(process.argv[3]);
const root=await mkdtemp(path.join(tmpdir(),'shared-terminal-tab-record-serial-ui-中文-'));
let ui,report;
try {
  const bin=path.join(root,'bin'),data=path.join(root,'data');
  await mkdir(bin);
  const executable=path.join(bin,'shared-terminal-desktop.exe');
  await copyFile(desktop,executable);
  await copyFile(fixture,path.join(bin,'session-service.exe'));
  ui=await launchDesktop(data,{fixture:true,executable});
  const service=await ui.invoke('service_status');
  assert.equal(service.fixture,true);
  await ui.click('串口连接');
  const ports='document.querySelector(\'[aria-label="UART端口"]\').options';
  await ui.waitFor(`document.querySelector('[aria-label="UART端口"]')?.options.length===2`);
  const port=await ui.evaluate(`${ports}[1].textContent`);
  assert.match(port,/\bCOM7\b/);
  await ui.fill('UART端口',await ui.evaluate(`${ports}[1].value`));
  await ui.fill('UART波特率',57600);
  await ui.click('连接串口');
  await ui.waitFor(`!document.querySelector('dialog:modal')`);
  const uart=(await ui.invoke('service_list')).find(c=>c.protocol==='SERIAL');
  assert.ok(uart);
  const connection={connection_id:uart.connection_id,generation:uart.generation};
  const button=`document.querySelector('[data-connection-id="${uart.connection_id}"]')?.parentElement.querySelector('.tab-record-button')`;
  const state=s=>ui.waitFor(`(${button})?.dataset.recording==='${s}'`);
  const status=()=>ui.invoke('logging_request',{request:{op:'list',connection}}).then(result=>result.logs[0]);
  const click=async()=>{await ui.waitFor(`(${button})?.getAttribute('aria-disabled')==='false'`);await ui.evaluate(`(${button}).click()`);};
  await state('idle');
  await click();await state('recording');
  const log=await status();
  assert.equal(log.protocol,'SERIAL'); assert.deepEqual(log.connection,connection);
  const filename=path.join(data,'logs',log.readable.filename);
  assert.equal(path.dirname(filename),path.join(data,'logs'));
  const marker='Android启动 log';
  for(let i=0;i<100;i++){
    if(await readFile(filename,'utf8').then(text=>text.includes(marker)).catch(()=>false))break;
    await delay(30);
  }
  assert.ok((await readFile(filename,'utf8')).includes(marker));
  await ui.screenshot('desktop-0.1.4-serial-recording.png');
  const lost=await ui.interceptIpc({op:'stop',connectionId:uart.connection_id,mode:'error'});
  await click();await state('unknown');
  assert.equal(await ui.evaluate(`document.querySelector('.toolbar-log').textContent`),'状态未知');
  assert.equal(await lost.count(),1);
  const pending=await ui.evaluate(`JSON.parse(sessionStorage.getItem('terminal-tab-recording-v1'))[0][1]`);
  assert.deepEqual(pending,{kind:'stop',id:log.log_id});
  await lost.restore();
  const noReplay=await ui.interceptIpc({op:'stop',connectionId:uart.connection_id,mode:'error'});
  await click();await state('idle');
  assert.equal(await noReplay.count(),0);
  await noReplay.restore();
  const stopped=await status();
  assert.equal(stopped.log_id,log.log_id);
  assert.ok(stopped.worker_finished&&stopped.durable);
  assert.equal(stopped.readable.synced_bytes,stopped.readable.flushed_bytes);
  const final=await readFile(filename);
  assert.equal(final.length,stopped.readable.synced_bytes);
  assert.ok(final.includes(Buffer.from(marker)));
  const rendering=`document.querySelector('[data-pane][data-rendered-id="${uart.connection_id}"]')`;
  await ui.waitFor(`!!${rendering} && document.querySelector('.toolbar-log').textContent==='日志'`);
  await ui.evaluate(`document.querySelector('.toolbar-log').click()`);
  await ui.waitFor(`[...document.querySelectorAll('.terminal-context-menu button')].some(b=>b.textContent==='开始记录'&&!b.disabled)`);
  await ui.command('Input.dispatchKeyEvent',{type:'keyDown',key:'Escape',code:'Escape',windowsVirtualKeyCode:27});
  const close=await closeSoakDesktop(ui,data,service,{});
  report={result:'PASS',transport:'memory UART COM7',sameStopAfterLostReply:true,syncedBytes:final.length,menuUpdated:true,close};
} finally {
  await ui?.close();
  assert.equal(path.dirname(root),path.resolve(tmpdir()));
  assert.ok(path.basename(root).startsWith('shared-terminal-tab-record-serial-ui-中文-'));
  await rm(root,{recursive:true,force:true,maxRetries:20,retryDelay:100});
}
await writeFile('artifacts/windows-0.1.4-tab-recording-serial.json',JSON.stringify(report,null,2)+'\n');
console.log('PASS memory UART tab recording, file, durable stop and original-only lookup');
